def sync_db(db_path):
    if not os.path.exists(db_path):
        return
    conn = sqlite3.connect(db_path)
    cur = conn.cursor()

    # 1. Sync teams
    for t_id, name, desc in TEAMS:
        cur.execute("INSERT OR REPLACE INTO teams (id, team_name, description) VALUES (?, ?, ?)", (t_id, name, desc))

    # 2. Clear old users and insert the exact 19 Supabase users
    cur.execute("DELETE FROM users")
    for u in USERS:
        cur.execute("""
            INSERT INTO users (
                id, full_name, email, email_hash, email_original,
                employee_id, password, role_id, team_id, designation,
                phone, created_at, updated_at, approved, email_verified,
                is_active, status
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        """, (
            u["id"], u["full_name"], u["email"], u["email_hash"], u["email_original"],
            u["employee_id"], u["password"], u["role_id"], u["team_id"], u["designation"],
            u["phone"], u["created_at"], u["updated_at"], u["approved"], u["email_verified"],
            u["is_active"], u["status"]
        ))
    conn.commit()
    conn.close()
    print(f"Successfully synced {len(USERS)} Supabase users to {db_path}")

